/// Logical key identifiers supported by the terminal input system.
enum KeyCode {
  // Printable & basic characters
  character,
  space,
  tab,
  enter,
  backspace,
  escape,
  delete,
  insert,

  // Navigation
  arrowUp,
  arrowDown,
  arrowLeft,
  arrowRight,
  pageUp,
  pageDown,
  home,
  end,

  // Function keys
  f1,
  f2,
  f3,
  f4,
  f5,
  f6,
  f7,
  f8,
  f9,
  f10,
  f11,
  f12,

  // Special
  unknown,
}
